using System.Text;
using Brovan.WinFacts.Readers;

namespace Brovan.WinFacts.Rules
{
    internal sealed record VersionInputs(ushort Build, ushort Revision, PeImage Image, PdbPublics Publics);

    internal sealed record VersionResult(ushort Build, ushort Revision, string Facts, string Error)
    {
        internal string Version => $"{Build}.{Revision}";
    }

    internal sealed class SourceWriter
    {
        private readonly StringBuilder Text = new();

        internal void Line(string Value = "") => Text.Append(Value).Append("\r\n");

        public override string ToString() => Text.ToString();
    }

    internal abstract class FactGroup
    {
        internal static readonly FactGroup[] All = { new CompositionGroup() };

        internal abstract string Name { get; }

        internal abstract string KeyFile { get; }

        // Relative to the repository root.
        internal abstract string OutputPath { get; }

        protected abstract string Namespace { get; }

        protected abstract string SetClass { get; }

        // The expression Find gives for a version with no set.
        protected abstract string UnknownVersion { get; }

        // Versions whose set a Brovan run has exercised end to end.
        protected abstract (ushort Build, ushort Revision)[] RunVersions { get; }

        internal abstract string Extract(VersionInputs Inputs);

        protected abstract void WriteTypes(SourceWriter Code);

        protected abstract void WriteMembers(SourceWriter Code);

        protected abstract void WriteSet(SourceWriter Code, string Facts);

        // A set takes the name of its lowest version, so a new Windows update never renames the other sets.
        internal string Emit(IReadOnlyList<VersionResult> Results)
        {
            List<(string Name, string Facts, List<VersionResult> Members)> Sets = new();
            foreach (IGrouping<string, VersionResult> Same in Results.Where(Result => Result.Error == null).GroupBy(Result => Result.Facts))
            {
                List<VersionResult> Members = Same.OrderBy(Member => Member.Build).ThenBy(Member => Member.Revision).ToList();
                Sets.Add(($"Set{Members[0].Build}_{Members[0].Revision}", Same.Key, Members));
            }

            Sets.Sort((A, B) => (A.Members[0].Build, A.Members[0].Revision).CompareTo((B.Members[0].Build, B.Members[0].Revision)));
            SourceWriter Code = new();
            Code.Line("// <auto-generated>");
            Code.Line($"// Written by Brovan.WinFacts from {KeyFile} and its public PDB. Run the tool to change it, never by hand.");
            Code.Line("//");
            foreach ((string SetName, _, List<VersionResult> Members) in Sets)
            {
                bool Ran = Members.Any(Member => RunVersions.Contains((Member.Build, Member.Revision)));
                Code.Line($"// {SetName}: {Members.Count} version{(Members.Count == 1 ? "" : "s")}{(Ran ? "" : ", extracted, not run")}");
            }

            List<VersionResult> Left = Results.Where(Result => Result.Error != null).OrderBy(Result => Result.Build).ThenBy(Result => Result.Revision).ToList();
            if (Left.Count != 0)
            {
                Code.Line("//");
                Code.Line("// Left out:");
                foreach (VersionResult Result in Left)
                    Code.Line($"//   {Result.Version}: {Result.Error}");
            }

            Code.Line("// </auto-generated>");
            Code.Line();
            Code.Line("using System;");
            Code.Line();
            Code.Line($"namespace {Namespace}");
            Code.Line("{");
            WriteTypes(Code);
            Code.Line($"    internal sealed class {SetClass}");
            Code.Line("    {");
            Code.Line($"        internal const string KeyFile = \"{KeyFile}\";");
            Code.Line();
            WriteMembers(Code);
            foreach ((string SetName, string Facts, _) in Sets)
            {
                Code.Line();
                Code.Line($"        private static readonly {SetClass} {SetName} = new(");
                WriteSet(Code, Facts);
            }

            Code.Line();
            Code.Line($"        internal static {SetClass} Find(ushort Build, ushort Revision) => (Build, Revision) switch");
            Code.Line("        {");
            foreach ((VersionResult Member, string SetName) in Sets.SelectMany(Set => Set.Members.Select(Member => (Member, Set.Name)))
                         .OrderBy(Entry => Entry.Member.Build).ThenBy(Entry => Entry.Member.Revision))
                Code.Line($"            ({Member.Build}, {Member.Revision}) => {SetName},");

            Code.Line($"            _ => {UnknownVersion},");
            Code.Line("        };");
            Code.Line("    }");
            Code.Line("}");
            return Code.ToString();
        }
    }
}
